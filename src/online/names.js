/** Розподіл зразків: у звичайних героїв переважають родинні прізвища, у рідкісних частішають козацькі й прізвиська. */
const MIX = {
  c: [[FAMILY, 56], [CRAFT, 12], [NATURE, 10], [SKY, 10], [ADJ, 5], [COMPOUND, 4], [COSSACK, 3]],
  r: [[FAMILY, 46], [CRAFT, 10], [NATURE, 12], [SKY, 12], [ADJ, 6], [COMPOUND, 6], [COSSACK, 7], [EPIC, 1]],
  e: [[FAMILY, 26], [NATURE, 14], [SKY, 14], [ADJ, 6], [COMPOUND, 10], [COSSACK, 18], [EPIC, 12]],
  l: [[SKY, 12], [NATURE, 10], [COMPOUND, 10], [COSSACK, 30], [EPIC, 38]],
};
const rollSurname = (rar, rnd) => {
  const mix = MIX[rar] || MIX.c; let r = rnd() * 100;
  for (const [list, w] of mix) { r -= w; if (r < 0) return pick(list, rnd); }
  return pick(FAMILY, rnd);
};
/** Без «Назар Назаренко» й «Лев Левченко»: ім'я й прізвище не мають спільного кореня. */
const sameRoot = (first, last) => first.slice(0, 3).toLowerCase() === last.slice(0, 3).toLowerCase();

/**
 * Нове повне ім'я. used (Set) пам'ятає зайняте в команді: прізвища (за ними зараховуються голи) і імена з префіксом f:.
 * Довжина до 22 символів: стільки лишає суперникові fromWire.
 */
export function newName(used = new Set(), rar = 'c', rnd = Math.random) {
  let first = '', last = '';
  for (let i = 0; i < 300; i++) {
    first = pick(FIRST_NAMES, rnd); last = rollSurname(rar, rnd);
    if (used.has(last) || used.has('f:' + first) || sameRoot(first, last) || first.length + last.length + 1 > 22) continue;
    break;
  }
  used.add(last); used.add('f:' + first);
  return first + ' ' + last;
}

