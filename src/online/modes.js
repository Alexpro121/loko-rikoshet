// Режими онлайн-хабу: плитки вкладки «Матч» (screen.js). Новий режим, наприклад турнір, — новий запис тут; решту хабу міняти не треба.
// Поля: id, title, sub (підпис), on() — чи можна грати зараз, why — чому ні (лише правда: без дат і вигаданих даних),
// act — дія плитки (data-act, обробляє OnlineScreen.act), tab — якщо режиму потрібен свій екран: { name, ic, html(hub) },
// тоді хаб додає вкладку в нижню навігацію. Плитки «quick» і «friend» хаб малює сам: у них кнопки й поле коду.
import { I } from '../ui/icons.js';

export const MODES = [
  { id: 'quick', title: 'Швидкий матч', sub: 'Випадковий суперник із тих, хто зараз теж шукає гру', on: () => true, act: 'on-seek' },
  { id: 'friend', title: 'Гра з другом', sub: 'Кімната за кодом або посиланням', on: () => true },
  {
    id: 'cup', title: 'Турніри', ic: I.trophy, on: () => false,
    why: 'Для турнірів сервер гри має збирати учасників, вести сітку й підтверджувати результати',
  },
];

/** Вкладки режимів, яким потрібен свій екран (лише чинних). */
export const modeTabs = () => MODES.filter((m) => m.tab && m.on()).map((m) => ({ id: 'm-' + m.id, name: m.tab.name, ic: m.tab.ic, html: m.tab.html }));
