// Воксельні іконки в ізометрії: ті самі кубики, з яких складена гра, лише в SVG.
// Кожен блок — [x, y, z, ширина, глибина, висота, колір]; видно верх і дві передні грані.

const C30 = Math.cos(Math.PI / 6);
const P = (x, y, z) => [(x - y) * C30, (x + y) * 0.5 - z];

function shade(hex, k) {
  const n = parseInt(hex.slice(1), 16);
  const c = (v) => Math.max(0, Math.min(255, Math.round(v * k))).toString(16).padStart(2, '0');
  return '#' + c(n >> 16) + c((n >> 8) & 255) + c(n & 255);
}

function vox(blocks, pad = 0.35) {
  const polys = [];
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  // спершу нижчі шари (предмет на плиті малюється після плити), у шарі — від дальніх до ближчих
  const key = (q) => Math.floor(q[2] * 2) * 100 + q[0] + q[3] / 2 + q[1] + q[4] / 2;
  const sorted = blocks.slice().sort((a, b) => key(a) - key(b));
  for (const [x, y, z, a, b, c, col] of sorted) {
    const faces = [
      [[x, y, z + c], [x + a, y, z + c], [x + a, y + b, z + c], [x, y + b, z + c], shade(col, 1.1)],
      [[x, y + b, z], [x + a, y + b, z], [x + a, y + b, z + c], [x, y + b, z + c], shade(col, 0.84)],
      [[x + a, y, z], [x + a, y + b, z], [x + a, y + b, z + c], [x + a, y, z + c], shade(col, 0.64)],
    ];
    for (const f of faces) {
      const pts = f.slice(0, 4).map(([px, py, pz]) => P(px, py, pz));
      for (const [sx, sy] of pts) { x0 = Math.min(x0, sx); y0 = Math.min(y0, sy); x1 = Math.max(x1, sx); y1 = Math.max(y1, sy); }
      polys.push(`<path d="M${pts.map(([sx, sy]) => sx.toFixed(3) + ' ' + sy.toFixed(3)).join('L')}Z" fill="${f[4]}"/>`);
    }
  }
  const vb = [x0 - pad, y0 - pad, x1 - x0 + pad * 2, y1 - y0 + pad * 2].map((v) => v.toFixed(2)).join(' ');
  return `<svg class="vox" viewBox="${vb}" aria-hidden="true"><g stroke="#08140f" stroke-width="0.07" stroke-linejoin="round">${polys.join('')}</g></svg>`;
}

