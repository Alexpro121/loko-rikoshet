// Воксельні іконки в ізометрії: ті самі кубики, з яких складена гра, лише в SVG.
// Кожен блок — [x, y, z, ширина, глибина, висота, колір, частина?]; видно верх і дві передні грані (+y ліворуч, +x праворуч).
// Колір '!#…' — грані без обводки (розмітка поля, світлові цифри). Колір BALL_C — не блок, а м'яч у кубі [x, y, z, d, d, d]:
// круглий, з латками й тінню, бо м'яч із кубиків не впізнати.
// SVG будується один раз при імпорті. Блоки з назвою частини йдуть окремою групою <g class="vx-назва"> поверх решти,
// щоб CSS міг їх рухати (src/style.css, «предмети оживають»): частину став так, щоб її ніщо не закривало.

const C30 = Math.cos(Math.PI / 6);
const P = (x, y, z) => [(x - y) * C30, (x + y) * 0.5 - z];
const EPS = 1e-6, BALL_C = '@ball';
const r2 = (v) => Math.round(v * 100) / 100;

function shade(hex, k) {
  const n = parseInt(hex.slice(1), 16);
  const c = (v) => Math.max(0, Math.min(255, Math.round(v * k))).toString(16).padStart(2, '0');
  return '#' + c(n >> 16) + c((n >> 8) & 255) + c(n & 255);
}

/** Чи B ближче до глядача за A (1), далі (-1) або вони перетинаються (0). Глядач дивиться з боку +x, +y, +z. */
function nearer(A, B) {
  if (A[0] + A[3] <= B[0] + EPS || A[1] + A[4] <= B[1] + EPS || A[2] + A[5] <= B[2] + EPS) return 1;
  if (B[0] + B[3] <= A[0] + EPS || B[1] + B[4] <= A[1] + EPS || B[2] + B[5] <= A[2] + EPS) return -1;
  return 0;
}
/** Проєкції шестикутника блока на три нормалі ізометрії: якщо хоч одна не перекривається, блоки на екрані не стикаються. */
const span = ([x, y, z, a, b, c]) => [x - y - b, x + a - y, y - z - c, y + b - z, x - z - c, x + a - z];
const apart = (s, t) => { for (let k = 0; k < 6; k += 2) if (s[k + 1] <= t[k] + EPS || t[k + 1] <= s[k] + EPS) return true; return false; };
const depth = (q) => q[0] + q[3] / 2 + q[1] + q[4] / 2 + q[2] + q[5] / 2;

/** Порядок малювання: дальній блок раніше, ніж ближчий, якщо вони перекриваються на екрані (топологічне сортування). */
function order(bs) {
  const n = bs.length, sp = bs.map(span), after = bs.map(() => []), deg = new Array(n).fill(0);
  for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) {
    if (apart(sp[i], sp[j])) continue;
    let f = nearer(bs[i], bs[j]);
    if (!f) f = depth(bs[i]) <= depth(bs[j]) ? 1 : -1;                // перетин (так не будуй): за центром
    if (f > 0) { after[i].push(j); deg[j]++; } else { after[j].push(i); deg[i]++; }
  }
  const out = [], done = new Array(n).fill(false);
  for (let k = 0; k < n; k++) {
    let best = -1;
    for (let i = 0; i < n; i++) if (!done[i] && (best < 0 || (deg[i] === 0) > (deg[best] === 0) || ((deg[i] === 0) === (deg[best] === 0) && depth(bs[i]) < depth(bs[best])))) best = i;
    done[best] = true; out.push(bs[best]);
    for (const j of after[best]) deg[j]--;
  }
  return out;
}

/** Грань, яку повністю закриває сусідній блок упритул, не малюємо: менше вузлів у DOM. */
function hidden(q, bs, ax) {
  const o = [ax === 0 ? 1 : 0, ax === 2 ? 1 : 2], e = q[ax] + q[ax + 3];
  for (const b of bs) {
    if (b === q || b[6] === BALL_C || Math.abs(b[ax] - e) > EPS) continue;
    if (o.every((k) => b[k] <= q[k] + EPS && b[k] + b[k + 3] >= q[k] + q[k + 3] - EPS)) return true;
  }
  return false;
}

const K = Math.sqrt(1.5);   // наша ізометрія не зменшує осі: куля діаметром d на екрані має діаметр d·K
const pt = (cx, cy, r, a) => r2(cx + r * Math.cos(a)) + ' ' + r2(cy + r * Math.sin(a));
const pent = (cx, cy, r, rot) => 'M' + [0, 1, 2, 3, 4].map((k) => pt(cx, cy, r, rot + (k * 2 * Math.PI) / 5)).join('L') + 'Z';
/** М'яч: тінь на землі (окремо, щоб не стрибала разом із ним), біла куля, центральна латка, п'ять латок по колу, шви, затінений бік. */
function ballSvg([x, y, z, d]) {
  const [cx, cy] = P(x + d / 2, y + d / 2, z + d / 2), [gx, gy] = P(x + d / 2, y + d / 2, z), r = (d / 2) * K, U = -Math.PI / 2 + 0.2;
  const ox = cx - r * 0.06, oy = cy - r * 0.08;
  let seams = '', spots = pent(ox, oy, r * 0.3, U);
  for (let k = 0; k < 5; k++) {
    const a = U + (k * 2 * Math.PI) / 5;
    seams += 'M' + pt(ox, oy, r * 0.3, a) + 'L' + pt(ox, oy, r * 0.54, a);
    spots += pent(ox + r * 0.71 * Math.cos(a), oy + r * 0.71 * Math.sin(a), r * 0.19, a + Math.PI);
  }
  const a1 = -0.75, a2 = 2.35, R = r2(r), C = r2(cx) + '" cy="' + r2(cy) + '" r="' + R;   // затінений серпик праворуч знизу
  return {
    shadow: '<ellipse cx="' + r2(gx) + '" cy="' + r2(gy) + '" rx="' + r2((d / 2) * K * 0.95) + '" ry="' + r2((d / 2) * 0.68) + '" fill="#000" fill-opacity="0.28" stroke="none"/>',
    ball: '<circle cx="' + C + '" fill="' + CRM + '" stroke="none"/>'
      + '<path d="' + seams + '" fill="none" stroke-width="' + r2(Math.max(0.03, r * 0.07)) + '"/><path d="' + spots + '" fill="' + INK + '" stroke="none"/>'
      + '<path d="M' + pt(cx, cy, r, a1) + 'A' + R + ' ' + R + ' 0 0 1 ' + pt(cx, cy, r, a2) + 'A' + r2(r * 1.35) + ' ' + r2(r * 1.35) + ' 0 0 0 ' + pt(cx, cy, r, a1) + 'Z" fill="#000" fill-opacity="0.17" stroke="none"/>'
      + '<circle cx="' + C + '" fill="none"/>',
    box: [cx - r, cy - r, cx + r, cy + r],
  };
}

function vox(blocks, opt = {}) {
  const pad = opt.pad ?? 0.35, top = opt.top || 0, groups = new Map([['', []]]);
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  const grow = (sx, sy) => { x0 = Math.min(x0, sx); y0 = Math.min(y0, sy); x1 = Math.max(x1, sx); y1 = Math.max(y1, sy); };
  for (const q of blocks) { const g = q[7] || ''; if (!groups.has(g)) groups.set(g, []); groups.get(g).push(q); }
  let svg = '', under = '';
  for (const [name, list] of groups) {
    let polys = '';
    for (const q of order(list)) {
      const [x, y, z, a, b, c, col] = q;
      if (col === BALL_C) {                                           // тінь м'яча-частини лягає на основу, під усі частини
        const m = ballSvg(q); grow(m.box[0], m.box[1]); grow(m.box[2], m.box[3]);
        if (name) under += m.shadow; else polys += m.shadow;
        polys += m.ball; continue;
      }
      const bare = col[0] === '!', hex = bare ? col.slice(1) : col;
      const faces = [
        [2, [[x, y, z + c], [x + a, y, z + c], [x + a, y + b, z + c], [x, y + b, z + c]], 1.1],
        [1, [[x, y + b, z], [x + a, y + b, z], [x + a, y + b, z + c], [x, y + b, z + c]], 0.84],
        [0, [[x + a, y, z], [x + a, y + b, z], [x + a, y + b, z + c], [x + a, y, z + c]], 0.64],
      ];
      for (const [ax, f, k] of faces) {
        const pts = f.map(([px, py, pz]) => P(px, py, pz));
        for (const [sx, sy] of pts) grow(sx, sy);
        if (hidden(q, blocks, ax)) continue;
        polys += `<path d="M${pts.map(([sx, sy]) => r2(sx) + ' ' + r2(sy)).join('L')}Z" fill="${shade(hex, k)}"${bare ? ' stroke="none"' : ''}/>`;
      }
    }
    svg += name ? `<g class="vx-${name}">${polys}</g>` : polys;
  }
  const at = svg.indexOf('<g class="vx-');                         // основа йде першою: тіні частин стають одразу за нею
  if (under) svg = at < 0 ? svg + under : svg.slice(0, at) + under + svg.slice(at);
  const vb = [x0 - pad, y0 - pad - top, x1 - x0 + pad * 2, y1 - y0 + pad * 2 + top].map(r2).join(' ');
  return `<svg class="vox" viewBox="${vb}" aria-hidden="true"><g stroke="#08140f" stroke-width="0.07" stroke-linejoin="round">${svg}</g></svg>`;
}

