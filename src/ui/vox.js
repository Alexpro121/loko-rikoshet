const DIG = { 1: ['010', '110', '010', '010', '111'], 2: ['111', '001', '111', '100', '111'], ':': ['0', '1', '0', '1', '0'] };
function digits(str, x, y, zTop, p, col) {
  const out = [];
  for (const ch of str) {
    const g = DIG[ch];
    g.forEach((row, r) => { for (let c = 0; c < row.length; c++) if (row[c] === '1') { let e = c; while (row[e + 1] === '1') e++; out.push([x + c * p, y, zTop - (r + 1) * p, (e - c + 1) * p, 0.02, p, col]); c = e; } });
    x += g[0].length * p + p;
  }
  return out;
}
